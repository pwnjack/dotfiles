#!/bin/bash
#
# The one owner of the eww desktop clock: nothing else runs `eww open`,
# `eww close` or `eww reload` for it.
#
#   start    at login: open the clock if it is enabled and not already open
#   apply    after a setting changed: re-read the options, then close it when
#            disabled, or (re)open it with the new format, font and monitor
#   reload   after a palette change: reload a running clock, never start one
#
# Reads options/desktop-clock (enabled/disabled), desktop-clock-font,
# clock (12h, else 24 h) and mainmonitor (empty: monitor 0). Does nothing
# when eww is not installed.
#
# Every eww call has its stdio detached. The daemon forks from the first
# `eww open`; if it kept the caller's pipes, the settings panel (which waits
# for them to close) and wall.sh (which reads stderr to the end) would stall
# until the daemon exited.
#

set -uo pipefail

config_dir="${XDG_CONFIG_HOME:-$HOME/.config}"
cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}"
eww_dir="$config_dir/eww"
font_scss="$cache_dir/eww/font.scss"
default_font="Adwaita Sans"

command -v eww >/dev/null 2>&1 || exit 0

# A missing live option falls back to its tracked default: at the first login
# the overlay sync renders options/ in the background, possibly after this runs.
option() {
    local value="" file="$config_dir/options/$1"
    [ -e "$file" ] || file="$config_dir/defaults/options/$1"
    [ -r "$file" ] && IFS= read -r value < "$file"
    value=${value#"${value%%[![:space:]]*}"}
    printf '%s' "${value%"${value##*[![:space:]]}"}"
}

# Fd 9 is the lock below; the daemon must not inherit it, or it would hold
# the lock for as long as it lives.
ew() { eww --config "$eww_dir" "$@" </dev/null 9>&-; }

daemon_up() { ew ping >/dev/null 2>&1; }

clock_open() { ew active-windows 2>/dev/null | grep -q ': clock$'; }

start_daemon() {
    local _
    ew daemon >/dev/null 2>&1
    for _ in {1..40}; do
        daemon_up && return 0
        sleep 0.05
    done
    return 1
}

# The font reaches SCSS through a generated partial, not a tracked file and
# not an inline style. It is user text, and SCSS would evaluate `#{...}` in
# it or let a quote end the string, so anything but plain family-name
# characters falls back to the default.
render_font() {
    local font
    font=$(option desktop-clock-font)
    if [ -z "$font" ] || [[ "$font" == *[^[:alnum:]\ ._+-]* ]]; then
        [ -z "$font" ] || echo "desktop-clock: ignoring unsafe font name, using $default_font" >&2
        font=$default_font
    fi
    local text="// Generated by scripts/desktop-clock/desktop-clock.sh - do not edit
\$clock-font: \"$font\";"
    if [ -r "$font_scss" ] && [ "$(< "$font_scss")" = "$text" ]; then
        return 0
    fi
    mkdir -p "${font_scss%/*}"
    local tmp
    tmp=$(mktemp "$font_scss.XXXXXX") || return 1
    if ! { printf '%s\n' "$text" > "$tmp" && mv -f "$tmp" "$font_scss"; }; then
        rm -f "$tmp"
        return 1
    fi
}

# The stylesheet imports the colour partial, which only apply_wal_colors.sh
# writes; make sure it exists before eww parses the stylesheet.
ensure_colors() {
    [ -e "$cache_dir/wal/eww-colors.scss" ] || bash "$eww_dir/apply_wal_colors.sh" --no-reload
}

time_format() {
    if [ "$(option clock)" = 12h ]; then printf '%%I:%%M %%p'; else printf '%%H:%%M'; fi
}

# eww names a monitor by its model, not its connector, so options/mainmonitor
# (a connector) is looked up in Hyprland. Two monitors of one model cannot be
# told apart by name, and nothing here guesses: those, an unknown connector
# and an empty preference all leave the clock on monitor 0.
monitor_model() {
    local preferred json model count
    preferred=$(option mainmonitor)
    [ -n "$preferred" ] || return 0
    command -v hyprctl >/dev/null 2>&1 && command -v jq >/dev/null 2>&1 || return 0
    json=$(hyprctl monitors -j 2>/dev/null) || return 0
    model=$(jq -r --arg name "$preferred" '[.[] | select(.name == $name) | .model] | first // empty' <<< "$json" 2>/dev/null)
    [ -n "$model" ] || return 0
    count=$(jq -r --arg model "$model" '[.[] | select(.model == $model)] | length' <<< "$json" 2>/dev/null)
    [ "$count" = 1 ] && printf '%s' "$model"
}

open_clock() {
    local model out
    local -a screen=()
    model=$(monitor_model)
    [ -z "$model" ] || screen=(--screen "$model")
    if ! out=$(ew open clock "${screen[@]}" --arg "time_fmt=$(time_format)" 2>&1); then
        if [ "${#screen[@]}" -gt 0 ] && out=$(ew open clock --arg "time_fmt=$(time_format)" 2>&1); then
            return 0
        fi
        echo "desktop-clock: could not open the clock: $out" >&2
        return 1
    fi
}

close_clock() {
    daemon_up || return 0
    ew close clock >/dev/null 2>&1
    # The clock is the daemon's only window; with it gone nothing needs to stay resident.
    [ -n "$(ew active-windows 2>/dev/null)" ] && return 0
    ew kill >/dev/null 2>&1
    # kill only queues the shutdown, and the daemon still answers ping while it
    # exits. Hold the lock until it is gone, or a queued enable would reopen the
    # clock on a daemon that is about to vanish.
    local _
    for _ in {1..40}; do
        daemon_up || return 0
        sleep 0.05
    done
    echo "desktop-clock: the eww daemon did not stop" >&2
    return 1
}

# eww reports a stylesheet or config it cannot load to the client; pass that
# on, so neither the panel nor the palette driver reports a stale clock as done.
reload_style() {
    local out
    out=$(ew reload 2>&1) && return 0
    echo "desktop-clock: eww could not reload: $out" >&2
    return 1
}

cmd_apply() {
    if [ "$(option desktop-clock)" != enabled ]; then
        close_clock
        return 0
    fi
    render_font && ensure_colors || return 1
    if daemon_up; then
        # Closed first: a reload reopens windows with the arguments they had.
        ew close clock >/dev/null 2>&1
        reload_style || return 1
    else
        start_daemon || { echo "desktop-clock: the eww daemon did not start" >&2; return 1; }
    fi
    open_clock
}

cmd_start() {
    [ "$(option desktop-clock)" = enabled ] || return 0
    daemon_up && clock_open && return 0
    cmd_apply
}

cmd_reload() {
    daemon_up && clock_open || return 0
    render_font || return 1
    reload_style
}

main() {
    local lock="$cache_dir/eww/desktop-clock.lock"
    mkdir -p "${lock%/*}"
    exec 9> "$lock"
    command -v flock >/dev/null 2>&1 && flock 9

    case "${1:-}" in
        start) cmd_start ;;
        apply) cmd_apply ;;
        reload) cmd_reload ;;
        *) echo "usage: ${0##*/} start|apply|reload" >&2; return 2 ;;
    esac
}

main "$@"
