#!/bin/bash
#
# Renders docs/keybindings.md from hypr/config/software/keybinds.lua.
#
# README used to carry the full table by hand. It drifted, exactly the way the
# cheatsheet drifted before it was made self-rendering: bindings the config
# does not have, bindings the config has that the table omitted, and per-user
# values printed as though they were fixed. Moving a hand-written table to a new
# file relocates that problem, so this generates it instead.
#
# The rows come from `scripts/keybinds/keybinds-sheet.sh --markdown` rather than from a
# second parser here. One parse feeds both surfaces, so the document and the
# Super+H overlay cannot disagree; this script only supplies the prose around it.
#
# Usage: generate-keybindings.sh [--check]
#   (no args)  write docs/keybindings.md
#   --check    exit 1 with a diff when the tracked file is out of date;
#              this is what test/test-docs.sh runs.
#
set -uo pipefail

self_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$self_dir/../.." && pwd)"

cheatsheet="$root/scripts/keybinds/keybinds-sheet.sh"
out="$root/docs/keybindings.md"

if [ ! -x "$cheatsheet" ]; then
    echo "generate-keybindings: cannot run $cheatsheet" >&2
    exit 1
fi

render() {
    cat <<'PREAMBLE'
<!-- Generated by scripts/docs/generate-keybindings.sh. Do not edit by hand. -->

# Keybindings

Every row below is rendered from `hypr/config/software/keybinds.lua` by the
same parse that `Super + H` shows at runtime, so this file cannot disagree with
the bindings it documents. To change a binding, edit the config and regenerate:

```bash
./scripts/docs/generate-keybindings.sh
```

`test/test-docs.sh` fails when this file is out of date, so a stale copy cannot
be committed.

Rows that launch an application chosen in `options/` (the terminal, browser,
editors and file manager) print the option's name rather than one machine's
choice: Hyprland reads the file at parse time, so the answer is per-machine
and the Super + H overlay fills in your own. Everything else here is the same
on every checkout.

PREAMBLE
    "$cheatsheet" --markdown
}

if [ "${1:-}" = "--check" ]; then
    if [ ! -f "$out" ]; then
        echo "generate-keybindings: $out does not exist" >&2
        exit 1
    fi
    # Process substitution, not a pipe: the exit status has to be diff's.
    if ! diff -u "$out" <(render) >/dev/null; then
        echo "docs/keybindings.md is out of date. Regenerate with:" >&2
        echo "  ./scripts/docs/generate-keybindings.sh" >&2
        diff -u "$out" <(render) >&2
        exit 1
    fi
    exit 0
fi

# Rendered beside the document and renamed into place, so a failed render
# never leaves a truncated docs/keybindings.md behind.
tmp="$out.tmp.$$"
if ! render > "$tmp"; then
    rm -f -- "$tmp"
    echo "generate-keybindings: rendering failed; $out left unchanged" >&2
    exit 1
fi
mv -f -- "$tmp" "$out"
echo "wrote ${out#"$root"/}"
